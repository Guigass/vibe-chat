#!/usr/bin/env node
/**
 * B-165 — Embute version + buildId no cliente web.
 * Gera public/version.json e src/environments/version.generated.ts.
 */
import { execSync } from 'node:child_process';
import { createHash, randomBytes } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const version = typeof pkg.version === 'string' && pkg.version !== '0.0.0' ? pkg.version : '0.1.0';
const name = 'VibeChat.Web';

function shortBuildId() {
  const fromEnv =
    process.env.VIBECHAT_WEB_BUILD_ID ||
    process.env.GITHUB_SHA ||
    process.env.CI_COMMIT_SHA ||
    process.env.SOURCE_VERSION;
  if (fromEnv && /^[a-f0-9]+$/i.test(fromEnv.trim())) {
    return fromEnv.trim().slice(0, 12).toLowerCase();
  }
  try {
    const hash = execSync('git rev-parse --short=12 HEAD', {
      cwd: root,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
    if (hash) return hash;
  } catch {
    // outside git / shallow clone — fall through
  }
  const stamp = Date.now().toString(36);
  const noise = randomBytes(3).toString('hex');
  return createHash('sha1').update(`${stamp}-${noise}`).digest('hex').slice(0, 12);
}

const buildId = shortBuildId();
const payload = { name, version, buildId };
const json = `${JSON.stringify(payload, null, 2)}\n`;

writeFileSync(join(root, 'public', 'version.json'), json, 'utf8');

const generated = `/* Auto-generated by scripts/write-web-version.mjs — do not edit by hand. */
export const webVersion = {
  name: ${JSON.stringify(name)},
  version: ${JSON.stringify(version)},
  buildId: ${JSON.stringify(buildId)},
} as const;
`;

writeFileSync(join(root, 'src', 'environments', 'version.generated.ts'), generated, 'utf8');

console.log(`[write-web-version] ${name} ${version} buildId=${buildId}`);
