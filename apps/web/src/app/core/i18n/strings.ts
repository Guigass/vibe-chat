export function fillTemplate(
  template: string,
  vars: Record<string, string | number>,
): string {
  let out = template;
  for (const [key, value] of Object.entries(vars)) {
    out = out.replaceAll(`%${key}%`, String(value));
  }
  return out;
}

export function translateErrorCode(code: string | undefined): string {
  switch (code) {
    case 'InvalidLocale':
      return ui.errorInvalidLocale;
    case 'MentionAllForbidden':
      return ui.errorMentionAllForbidden;
    case 'InvalidEmoji':
      return ui.errorInvalidEmoji;
    case 'WrongChannel':
      return ui.errorWrongChannel;
    case 'PinLimitReached':
      return ui.errorPinLimitReached;
    case 'NoteTooLong':
      return ui.errorNoteTooLong;
    case 'MessageBodyTooLong':
      return ui.errorMessageBodyTooLong;
    default:
      return code ?? '';
  }
}
